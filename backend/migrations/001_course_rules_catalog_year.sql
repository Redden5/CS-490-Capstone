-- REVIEW ONLY: apply manually to Supabase PostgreSQL after backup/schema review.
-- No catalog IDs are assumed. Legacy undated rules remain undated and unresolved.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';
LOCK TABLE public.courserule, public.ruleclause, public.rulecourse IN ACCESS EXCLUSIVE MODE;

ALTER TABLE public.courserule
    ADD COLUMN catalog_year_id bigint REFERENCES public.catalogyear(catalog_year_id),
    ADD COLUMN source_url text,
    ADD COLUMN parse_status text NOT NULL DEFAULT 'NEEDS_REVIEW',
    ADD COLUMN review_flags jsonb NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN source_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN content_sha256 varchar(64);

-- Find the old constraint by its column set, not an environment-specific name.
DO $$
DECLARE old_constraint record;
BEGIN
    FOR old_constraint IN
        SELECT c.conname FROM pg_constraint c
        WHERE c.conrelid = 'public.courserule'::regclass AND c.contype = 'u'
        AND (SELECT array_agg(a.attname::text ORDER BY a.attname)
             FROM unnest(c.conkey) k(attnum)
             JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k.attnum)
            = ARRAY['course_id','rule_type']::text[]
    LOOP
        EXECUTE format('ALTER TABLE public.courserule DROP CONSTRAINT %I', old_constraint.conname);
    END LOOP;
END $$;

ALTER TABLE public.courserule
    ADD CONSTRAINT courserule_course_type_year_key UNIQUE(course_id, rule_type, catalog_year_id),
    ADD CONSTRAINT courserule_parse_status_check
        CHECK (parse_status IN ('READY_FOR_SEED_REVIEW','NEEDS_REVIEW')),
    ADD CONSTRAINT courserule_review_flags_array_check CHECK (jsonb_typeof(review_flags) = 'array'),
    ADD CONSTRAINT courserule_source_metadata_object_check CHECK (jsonb_typeof(source_metadata) = 'object'),
    ADD CONSTRAINT courserule_fingerprint_check CHECK(content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
    ADD CONSTRAINT courserule_dated_machine_check
        CHECK (catalog_year_id IS NULL OR (machine_checkable IS NOT NULL AND
               (NOT machine_checkable OR
                (parse_status = 'READY_FOR_SEED_REVIEW' AND review_flags = '[]'::jsonb AND content_sha256 IS NOT NULL))));

-- NULL is retained only for legacy compatibility, not accepted by the new seeder.
CREATE UNIQUE INDEX courserule_legacy_undated_key
    ON public.courserule(course_id,rule_type) WHERE catalog_year_id IS NULL;
CREATE INDEX courserule_year_status_idx ON public.courserule(catalog_year_id,parse_status);

-- Some installations have plain bigint PKs, others already use serial/identity.
-- Supply generated IDs only when no generator exists; retain every existing ID.
DO $$
DECLARE entry record; current_default text; identity_kind text; seq_name text; next_id bigint;
BEGIN
    FOR entry IN SELECT * FROM (VALUES
        ('courserule','rule_id'), ('ruleclause','clause_id'), ('rulecourse','rule_course_id')
    ) AS ids(table_name,column_name)
    LOOP
        SELECT pg_get_expr(d.adbin,d.adrelid), a.attidentity::text
          INTO current_default, identity_kind
          FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
          WHERE a.attrelid=format('public.%I',entry.table_name)::regclass AND a.attname=entry.column_name;
        IF current_default IS NULL AND identity_kind = '' THEN
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
                           entry.table_name,entry.column_name);
            seq_name := pg_get_serial_sequence(format('public.%I',entry.table_name),entry.column_name);
            EXECUTE format('SELECT COALESCE(max(%I),0)+1 FROM public.%I',entry.column_name,entry.table_name) INTO next_id;
            PERFORM setval(seq_name::regclass,next_id,false);
        END IF;
    END LOOP;
END $$;

COMMENT ON COLUMN public.courserule.machine_checkable IS
    'Complete representable course rule, not verified student eligibility. Also require a dated year and READY_FOR_SEED_REVIEW.';
COMMENT ON COLUMN public.courserule.source_metadata IS
    'Lossless parser course artifact: raw fields, ASTs, normalizations, external conditions, metadata checks, missing references.';
COMMIT;
